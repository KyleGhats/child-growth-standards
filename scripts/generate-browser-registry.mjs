import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const pkgRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataRoot = path.join(pkgRoot, "dist", "data");
const outFile = path.join(pkgRoot, "src", "browser", "table-registry.generated.ts");

function walkJson(dir, base = dir) {
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walkJson(full, base));
    } else if (entry.name.endsWith(".json")) {
      files.push(path.relative(base, full).replace(/\\/g, "/"));
    }
  }
  return files;
}

function safeImportName(rel) {
  return `t_${rel.replace(/[^a-zA-Z0-9]/g, "_")}`;
}

if (!fs.existsSync(path.join(dataRoot, "nnc"))) {
  console.error("generate-browser-registry: run build:data first");
  process.exit(1);
}

const whoFiles = walkJson(path.join(dataRoot, "who"));
const nncFiles = walkJson(path.join(dataRoot, "nnc"));

const imports = [];
const whoEntries = [];
const nncEntries = [];

for (const rel of whoFiles) {
  const id = safeImportName(`who_${rel}`);
  imports.push(`import ${id} from "../../dist/data/who/${rel}" with { type: "json" };`);
  whoEntries.push(`  ["${rel.split("/").pop()}", ${id} as WhoTableFile],`);
}

for (const rel of nncFiles) {
  const id = safeImportName(`nnc_${rel}`);
  imports.push(`import ${id} from "../../dist/data/nnc/${rel}" with { type: "json" };`);
  const key = rel.replace(/\.json$/, "").split("/").pop();
  nncEntries.push(`  ["${key}", ${id} as DohTable],`);
}

const source = `// AUTO-GENERATED by scripts/generate-browser-registry.mjs — do not edit
import type { WhoTableFile } from "./who-load-tables.js";
import type { DohTable } from "./doh-load-tables.js";

${imports.join("\n")}

export const WHO_TABLES = new Map<string, WhoTableFile>([
${whoEntries.join("\n")}
]);

export const NNC_TABLES = new Map<string, DohTable>([
${nncEntries.join("\n")}
]);
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, source);
console.log(`generate-browser-registry: ${whoFiles.length} WHO + ${nncFiles.length} NNC tables`);
